// Helper to create ScoreboardModal-compatible historical IPL match objects
function makeIplMatch({
  id,
  season,
  stage,
  stageKind = 'playoff', // 'playoff' | 'league'
  dateLabel,
  venue,
  teamAKey,
  scoreA,
  oversA,
  teamBKey,
  scoreB,
  oversB,
  result,
  potm,
  innings = [],
  commentary = [],
  recentBalls = [],
}) {
  const fA = IPL_FRANCHISES[teamAKey] || { short: teamAKey, name: teamAKey, color: '#0D9488' }
  const fB = IPL_FRANCHISES[teamBKey] || { short: teamBKey, name: teamBKey, color: '#3B82F6' }

  const buildPlayers = (inn) => {
    const names = new Set()
    const players = []
    for (const b of inn?.batsmen || []) {
      if (!names.has(b.name)) {
        names.add(b.name)
        players.push({ id: b.name, name: b.name, shortName: b.name, role: 'BAT' })
      }
    }
    return players
  }

  return {
    id,
    sport: 'cricket',
    isIplArchive: true,
    season,
    stage,
    stageKind,
    league: `IPL ${season} • ${stage}`,
    leagueName: `IPL ${season}`,
    format: 'T20',
    status: 'ft',
    dateLabel,
    venue,
    potm,
    teamA: { short: fA.short, name: fA.name, color: fA.color, score: scoreA, overs: oversA },
    teamB: { short: fB.short, name: fB.name, color: fB.color, score: scoreB, overs: oversB },
    meta: { need: result, crr: '', lastWicket: potm ? `POTM: ${potm}` : '' },
    detail: {
      provider: 'ipl-archive',
      matchHeader: {
        status: result,
        name: `${fA.name} vs ${fB.name}`,
        description: `IPL ${season} — ${stage}`,
        matchType: 'T20',
        venue,
        date: dateLabel,
      },
      meta: {
        crr: innings[1]?.runRate || innings[0]?.runRate || '',
        lastWicket: potm ? `Player of the Match · ${potm}` : '',
        need: result,
      },
      recentBalls,
      innings,
      lineups: {
        home: { teamName: fA.name, teamShort: fA.short, color: fA.color, players: buildPlayers(innings[0]), subs: [] },
        away: { teamName: fB.name, teamShort: fB.short, color: fB.color, players: buildPlayers(innings[1]), subs: [] },
      },
      commentary,
    },
  }
}

